const dateFormat = new Intl.DateTimeFormat("en-US", {
  month: "short",
  day: "numeric",
  year: "numeric"
});

function parseDate(dateStr) {
  return dateStr ? new Date(`${dateStr}T00:00:00`) : null;
}

function isUpcoming(show) {
  const start = parseDate(show.startDate);
  const end = parseDate(show.endDate) || start;
  if (!start || !end) return false;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return end >= today;
}

function isPast(show) {
  const end = parseDate(show.endDate) || parseDate(show.startDate);
  if (!end) return false;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return end < today;
}

function formatDateRange(show) {
  const start = parseDate(show.startDate);
  const end = parseDate(show.endDate);
  if (!start) return "";
  if (end && end > start) {
    return `${dateFormat.format(start)} – ${dateFormat.format(end)}`;
  }
  return dateFormat.format(start);
}

function createShowCard(show) {
  const card = document.createElement("article");
  card.className = "show-card";
  const img = document.createElement("img");
  img.src = show.image || "images/coming-soon.png";
  img.alt = show.name;
  card.appendChild(img);

  const title = document.createElement("h3");
  title.textContent = show.name;
  card.appendChild(title);

  const date = document.createElement("p");
  date.className = "date";
  date.textContent = formatDateRange(show);
  card.appendChild(date);

  const desc = document.createElement("p");
  desc.className = "muted";
  desc.textContent = show.description || "Details coming soon.";
  card.appendChild(desc);

  const actions = document.createElement("div");
  actions.className = "show-actions";

  if (show.infoLink) {
    const more = document.createElement("a");
    more.className = "btn ghost";
    more.href = show.infoLink;
    more.target = "_blank";
    more.rel = "noreferrer";
    more.textContent = "Event details";
    actions.appendChild(more);
  }

  if (show.mapEmbed) {
    const detailsEl = document.createElement("details");
    const summary = document.createElement("summary");
    summary.textContent = "Map";
    detailsEl.appendChild(summary);
    const mapWrap = document.createElement("div");
    mapWrap.innerHTML = show.mapEmbed;
    detailsEl.appendChild(mapWrap);
    card.appendChild(detailsEl);
  }

  if (actions.children.length) {
    card.appendChild(actions);
  }

  return card;
}

function renderUpcomingShows(targetId, limit = 3) {
  const container = document.getElementById(targetId);
  if (!container) return;
  const upcoming = shows.filter(isUpcoming).sort((a, b) => parseDate(a.startDate) - parseDate(b.startDate));
  const list = limit ? upcoming.slice(0, limit) : upcoming;
  if (!list.length) {
    container.innerHTML = `<p class="muted">New dates are on the way. Check back soon.</p>`;
    return;
  }
  container.innerHTML = "";
  container.classList.toggle("is-single", list.length === 1);
  list.forEach(show => container.appendChild(createShowCard(show)));
}

function renderShowList(targetId, filter = "upcoming") {
  const container = document.getElementById(targetId);
  if (!container) return;
  let list = [...shows].sort((a, b) => parseDate(a.startDate) - parseDate(b.startDate));
  if (filter === "upcoming") {
    list = list.filter(isUpcoming);
  } else if (filter === "past") {
    list = list.filter(isPast).reverse();
  }

  container.innerHTML = "";
  if (!list.length) {
    container.innerHTML = `<p class="muted">No shows in this view yet.</p>`;
    return;
  }

  container.classList.toggle("is-single", list.length === 1);
  list.forEach(show => container.appendChild(createShowCard(show)));
}

function setupShowFilters() {
  const buttons = document.querySelectorAll("[data-filter]");
  if (!buttons.length) return;
  let current = "upcoming";

  const activate = filter => {
    current = filter;
    buttons.forEach(btn => btn.classList.toggle("is-active", btn.dataset.filter === filter));
    renderShowList("shows-grid", filter);
  };

  buttons.forEach(btn => {
    btn.addEventListener("click", () => activate(btn.dataset.filter));
  });

  activate(current);
}

function renderFlavorChips(targetId) {
  const container = document.getElementById(targetId);
  if (!container) return;
  const top = [...appleFlavors].sort((a, b) => b.popularity - a.popularity).slice(0, 5);
  top.forEach(flavor => {
    const chip = document.createElement("span");
    chip.className = "badge";
    chip.textContent = flavor.name;
    container.appendChild(chip);
  });
}

function buildOrderForm() {
  const grid = document.getElementById("flavor-grid");
  if (!grid) return;

  const sorted = [...appleFlavors].sort((a, b) => b.popularity - a.popularity);
  sorted.forEach(flavor => {
    const card = document.createElement("div");
    card.className = "flavor-card";

    const label = document.createElement("label");
    label.htmlFor = `qty-${flavor.id}`;
    label.textContent = flavor.name;

    const img = document.createElement("img");
    img.src = flavor.image || "images/coming-soon.png";
    img.alt = flavor.name;

    const meta = document.createElement("div");
    meta.className = "flavor-meta";
    meta.innerHTML = `<span>Popularity</span><span>${flavor.popularity}/10</span>`;

    const input = document.createElement("input");
    input.type = "number";
    input.min = "0";
    input.value = "0";
    input.id = `qty-${flavor.id}`;
    input.dataset.flavorId = flavor.id;
    input.addEventListener("input", updateOrderSummary);

    card.append(label, img, meta, input);
    grid.appendChild(card);
  });

  const suggest = document.querySelector('[data-action="suggest"]');
  suggest?.addEventListener("click", () => {
    sorted.slice(0, 6).forEach(flavor => {
      const input = document.getElementById(`qty-${flavor.id}`);
      if (input) input.value = "1";
    });
    updateOrderSummary();
  });

  const clear = document.querySelector('[data-action="clear"]');
  clear?.addEventListener("click", () => {
    grid.querySelectorAll("input").forEach(input => (input.value = "0"));
    updateOrderSummary();
  });

  document.getElementById("submit-order")?.addEventListener("click", sendOrderEmail);
  document.getElementById("copy-summary")?.addEventListener("click", copySummaryToClipboard);

  updateOrderSummary();
}

function collectOrder() {
  const inputs = document.querySelectorAll("#flavor-grid input");
  const chosen = [];
  inputs.forEach(input => {
    const qty = parseInt(input.value, 10) || 0;
    if (qty > 0) {
      const flavor = appleFlavors.find(f => f.id === input.dataset.flavorId);
      if (flavor) {
        chosen.push({ flavor, qty });
      }
    }
  });

  const totalApples = chosen.reduce((sum, item) => sum + item.qty, 0);
  const pricePerApple = totalApples >= 25 ? 8 : 10;
  const total = totalApples * pricePerApple;

  const lines = chosen.map(item => `${item.qty} × ${item.flavor.name} @ $${pricePerApple} = $${item.qty * pricePerApple}`);
  const summaryText = [
    "Apple Purchase Request",
    "",
    ...lines,
    "",
    `Total apples: ${totalApples}`,
    `Price per apple: $${pricePerApple}`,
    `Estimated total: $${total}`
  ].join("\n");

  return { chosen, totalApples, pricePerApple, total, summaryText };
}

function updateOrderSummary() {
  const summaryEl = document.getElementById("order-summary");
  if (!summaryEl) return;
  const { chosen, totalApples, pricePerApple, total } = collectOrder();

  if (!totalApples) {
    summaryEl.innerHTML = `<p class="muted">Select flavors to see your estimated total.</p>`;
    return;
  }

  const list = chosen
    .map(item => `<li>${item.qty} × ${item.flavor.name} @ $${pricePerApple} = $${item.qty * pricePerApple}</li>`)
    .join("");

  summaryEl.innerHTML = `
    <p><strong>Total apples:</strong> ${totalApples}</p>
    <p><strong>Price per apple:</strong> $${pricePerApple}</p>
    <ul>${list}</ul>
    <p><strong>Estimated total:</strong> $${total}</p>
  `;
}

function sendOrderEmail() {
  const { totalApples, summaryText } = collectOrder();
  if (!totalApples) {
    alert("Add at least one apple to your request.");
    return;
  }

  const subject = encodeURIComponent("Apple Purchase Request");
  const body = encodeURIComponent(summaryText + "\nPickup preference: ");
  window.location.href = `mailto:enrightsapples@gmail.com?subject=${subject}&body=${body}`;
}

function copySummaryToClipboard() {
  const { totalApples, summaryText } = collectOrder();
  if (!totalApples) {
    alert("Add at least one apple to copy a summary.");
    return;
  }
  if (navigator.clipboard?.writeText) {
    navigator.clipboard.writeText(summaryText).then(() => {
      alert("Summary copied. Paste into any message.");
    });
  } else {
    alert("Clipboard is unavailable in this browser.");
  }
}

function setupNavToggle() {
  const toggle = document.querySelector("[data-nav-toggle]");
  if (!toggle) return;
  toggle.addEventListener("click", () => {
    document.body.classList.toggle("nav-open");
  });
  document.querySelectorAll("[data-nav] a").forEach(link => {
    link.addEventListener("click", () => document.body.classList.remove("nav-open"));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setupNavToggle();
  const page = document.body.dataset.page;
  if (page === "home") {
    renderUpcomingShows("upcoming-shows", 4);
    renderFlavorChips("hero-flavors");
  }
  if (page === "shows") {
    setupShowFilters();
  }
  if (page === "order") {
    buildOrderForm();
  }
});
